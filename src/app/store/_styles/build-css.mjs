// Builds src/app/store/_styles/store.css: Tailwind utilities for /store only, scoped to .at-store.
// The store does not depend on the app's Tailwind pipeline. Rerun after changing classes in /store:
//   node src/app/store/_styles/build-css.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";

const here = path.dirname(fileURLToPath(import.meta.url));
const storeDir = path.resolve(here, "..");
const root = path.resolve(storeDir, "../../..");
const require = createRequire(path.join(root, "package.json"));
const { compile, optimize } = require("@tailwindcss/node");
const { Scanner } = require("@tailwindcss/oxide");

const input = `
@layer theme, base, components, utilities;
@import "tailwindcss/theme.css" layer(theme);
@import "tailwindcss/utilities.css" layer(utilities);
`;

const compiler = await compile(input, { base: root, onDependency: () => {} });
const scanner = new Scanner({
  sources: [{ base: storeDir, pattern: "**/*.{ts,tsx}", negated: false }],
});
const candidates = scanner.scan();
let css = compiler.build(candidates);
// Scope theme variables to the store wrapper so they never touch the rest of the app.
css = css.replace(/:root,\s*:host\s*\{/g, ".at-store {");

const reset = `
body:has(.at-store) { margin: 0; background-color: #F6F3EC; }
@layer base {
  .at-store *, .at-store ::before, .at-store ::after { box-sizing: border-box; margin: 0; padding: 0; border: 0 solid; }
  .at-store h1, .at-store h2, .at-store h3, .at-store h4, .at-store p, .at-store dl, .at-store dd, .at-store figure { margin: 0; }
  .at-store h1, .at-store h2, .at-store h3, .at-store h4 { font-size: inherit; font-weight: inherit; }
  .at-store a { color: inherit; text-decoration: inherit; }
  .at-store ul, .at-store ol { list-style: none; }
  .at-store img, .at-store svg { display: block; vertical-align: middle; max-width: 100%; }
  .at-store button, .at-store input, .at-store select, .at-store textarea {
    font: inherit; color: inherit; background-color: transparent; border-radius: 0;
  }
  .at-store button { cursor: pointer; }
  .at-store button:disabled { cursor: not-allowed; }
  .at-store fieldset { min-width: 0; }
  .at-store table { border-collapse: collapse; text-indent: 0; }
  .at-store code { font-family: ui-monospace, SFMono-Regular, Menlo, monospace; }
  .at-store input::placeholder { opacity: 1; }
}
`;

const out = optimize(css + reset, { minify: false }).code;
const header = "/* Generated by build-css.mjs. Do not edit by hand. Tailwind utilities for /store, scoped to .at-store. */\n";
fs.writeFileSync(path.join(here, "store.css"), header + out);
console.log(`store.css: ${candidates.length} candidates, ${out.length} bytes`);
